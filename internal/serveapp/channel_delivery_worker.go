func (d *serveChannelDeliveryDispatcher) planOpenChannelCards(ctx context.Context) error {
	for _, status := range []string{decisioncard.StatusPending, "deferred"} {
		cursor := ""
		for {
			cards, next, err := d.cards.ListDecisionCards(ctx, decisioncard.ListOptions{Status: status, Limit: 200, Cursor: cursor})
			if err != nil {
				return err
			}
			for _, card := range cards {
				if _, err := d.store.PlanOpenChannelCard(ctx, card.CardID); err != nil {
					return fmt.Errorf("plan open channel card %s: %w", card.CardID, err)
				}
			}
			if next == "" {
				break
			}
			if next == cursor {
				return fmt.Errorf("channel card pagination did not advance")
			}
			cursor = next
		}
	}
	return nil
}

// reconcileDeliveries traverses canonical sources before selected
// responsibilities. A receipt, including an uncertain one, is never inferred
// from a provider response or regenerated by this scan.
func (d *serveChannelDeliveryDispatcher) reconcileDeliveries(ctx context.Context) error {
	if d == nil || d.store == nil || d.cards == nil {
		return fmt.Errorf("channel delivery source owners are unavailable")
	}
	if err := d.reconcileCardChanges(ctx); err != nil {
		return err
	}
	if err := d.planOpenChannelCards(ctx); err != nil {
		return err
	}
	activationID, found, err := d.store.CurrentChannelDeliveryActivationID(ctx)
	if err != nil {
		return err
	}
	if !found || activationID == "" {
		return nil
	}
	cursor := ""
	var failures error
	for {
		plans, err := d.store.ListCurrentChannelDeliveryPlans(ctx, cursor, 200)
		if err != nil {
			return errors.Join(failures, err)
		}
		for _, candidate := range plans {
			failures = errors.Join(failures, d.reconcileDelivery(ctx, candidate))
		}
		if len(plans) < 200 {
			break
		}
		last := plans[len(plans)-1].DeliveryID
		if last == cursor {
			return errors.Join(failures, fmt.Errorf("channel delivery pagination did not advance"))
		}
		cursor = last
	}
	return failures
}

func (d *serveChannelDeliveryDispatcher) reconcileDelivery(ctx context.Context, candidate runtimechanneldelivery.Candidate) error {
	current, found, err := d.store.GetCurrentChannelDeliveryPlan(ctx, candidate.DeliveryID)
	if err != nil || !found {
		return err
	}
	candidate = current
	if candidate.RecoveryPending {
		return nil
	}
	if candidate.State == "uncertain" || candidate.State == "retired" {
		return nil
	}
	if candidate.State != "planned" && candidate.State != "rendered" && candidate.State != "sent" {
		return fmt.Errorf("channel delivery %s has unsupported state %q", candidate.DeliveryID, candidate.State)
	}
	bounds, capabilities, err := d.selectedPresentation(ctx, candidate)
	if err != nil {
		return fmt.Errorf("select channel delivery %s presentation bounds: %w", candidate.DeliveryID, err)
	}
	if candidate.CurrentReceiptID != "" && !capabilities.Vector().Edit {
		return nil
	}
	prepared, err := d.store.FreezeAndPersistChannelRender(ctx, candidate.DeliveryID, bounds)
	if err != nil {
		return fmt.Errorf("freeze channel delivery %s: %w", candidate.DeliveryID, err)
	}
	current, found, err = d.store.GetCurrentChannelDeliveryPlan(ctx, candidate.DeliveryID)
	if err != nil {
		return fmt.Errorf("read channel delivery %s: %w", candidate.DeliveryID, err)
	}
	if !found || current.RecoveryPending || current.CurrentRenderID != prepared.RenderID {
		return nil
	}
	if current.CurrentReceiptID == "" {
		if current.State != "rendered" {
			return nil
		}
		if err := d.dispatchInitial(ctx, current, prepared); err != nil {
			return fmt.Errorf("dispatch channel delivery %s: %w", candidate.DeliveryID, err)
		}
		return nil
	}
	receipt, found, err := d.store.GetCurrentChannelSentReceipt(ctx, candidate.DeliveryID, current.CurrentReceiptID)
	if err != nil {
		return fmt.Errorf("read channel delivery receipt %s: %w", current.CurrentReceiptID, err)
	}
	if !found {
		return fmt.Errorf("current channel delivery receipt %s is absent", current.CurrentReceiptID)
	}
	if receipt.RenderID == prepared.RenderID {
		return nil
	}
	if current.State != "rendered" {
		return fmt.Errorf("channel delivery %s has a changed render outside edit state", candidate.DeliveryID)
	}
	if err := d.dispatchEdit(ctx, current, prepared, receipt); err != nil {
		return fmt.Errorf("edit channel delivery %s: %w", candidate.DeliveryID, err)
	}
	return nil
}

func (d *serveChannelDeliveryDispatcher) reconcileCardChanges(ctx context.Context) error {
	cursor, current, err := d.store.CurrentChannelCardChangeCursor(ctx)
	if err != nil || !current {
		return err
	}
	for {
		changes, err := d.cards.ListDecisionCardChanges(ctx, decisioncard.SubscriptionOptions{After: cursor, Limit: 200})
		if err != nil {
			return err
		}
		for _, change := range changes {
			if change.Sequence <= cursor {
				return fmt.Errorf("channel card change cursor did not advance")
			}
			if err := d.store.PlanChangedChannelCard(ctx, change.Sequence, change.CardID); err != nil {
				return fmt.Errorf("plan channel card change %d: %w", change.Sequence, err)
			}
			cursor = change.Sequence
		}
		if len(changes) < 200 {
			return nil
		}
	}
}

func (d *serveChannelDeliveryDispatcher) reconcileCardActions(ctx context.Context) error {
	if d == nil || d.store == nil || d.cards == nil {
		return fmt.Errorf("channel action owners are unavailable")
	}
	cursor := ""
	var failures error
	for {
		pending, err := d.store.ListPendingChannelActions(ctx, cursor, 200)
		if err != nil {
			return errors.Join(failures, err)
		}
		for _, intent := range pending {
			if err := d.processPendingChannelAction(ctx, intent); err != nil {
				failures = errors.Join(failures, fmt.Errorf("process channel action %s: %w", intent.PublicationID, err))
			}
		}
		if len(pending) < 200 {
			return failures
		}
		last := pending[len(pending)-1].PublicationID
		if last == cursor {
			return errors.Join(failures, fmt.Errorf("channel action pagination did not advance"))
		}
		cursor = last
	}
}

func (d *serveChannelDeliveryDispatcher) processPendingChannelAction(ctx context.Context, intent runtimechanneldelivery.PendingAction) error {
	resolved, found, err := d.store.ResolveChannelActionFact(ctx, intent.Fact.ActionFact)
	if err != nil {
		return fmt.Errorf("resolve: %w", err)
	}
	if !found || !resolved.CurrentRender {
		return d.store.SettleUnappliedChannelAction(ctx, intent.Fact, runtimechanneldelivery.ActionRejected)
	}
	ackErr := d.acknowledgeChannelAction(ctx, intent, resolved)
	actionErr := d.processResolvedChannelAction(ctx, intent, resolved)
	var unsupported *runfork.SelectedForkControlUnsupported
	if errors.As(actionErr, &unsupported) {
		actionErr = d.store.SettleUnappliedChannelAction(ctx, intent.Fact, runtimechanneldelivery.ActionUnsupported)
	}
	return errors.Join(ackErr, actionErr)
}

func (d *serveChannelDeliveryDispatcher) processResolvedChannelAction(ctx context.Context, intent runtimechanneldelivery.PendingAction, resolved runtimechanneldelivery.ResolvedAction) error {
	switch resolved.Action.Kind {
	case "open_inbox", "view_full", "next_page":
		inboxText := ""
		var err error
		if resolved.Action.Kind == "open_inbox" {
			inboxText, err = d.inboxContent(ctx)
		}
		if err != nil {
			return err
		}
		_, err = d.store.PlanChannelActionResponse(ctx, intent.Fact, resolved, inboxText)
		return err
	case "more_controls":
		return d.store.AdvanceChannelActionPage(ctx, intent.Fact, resolved)
	case "acknowledge_notice":
		if resolved.SourceKind == "notice" {
			return d.processNoticeAction(ctx, intent, resolved)
		}
	case "select_draft":
		if resolved.SourceKind == "response" {
			return d.processDraftChoice(ctx, intent, resolved)
		}
	case "resend":
		if resolved.SourceKind == "response" {
			_, err := d.store.PlanManualChannelResend(ctx, intent.Fact, resolved)
			return err
		}
	case "skip_input":
		if resolved.TargetCardID() != "" {
			return d.processInputSkip(ctx, intent, resolved)
		}
	case "verdict", "cancel_input":
		if resolved.TargetCardID() != "" {
			return d.processCurrentCardAction(ctx, intent, resolved)
		}
	}
	return d.store.SettleUnappliedChannelAction(ctx, intent.Fact, runtimechanneldelivery.ActionUnsupported)
}

func (d *serveChannelDeliveryDispatcher) processCurrentCardAction(ctx context.Context, intent runtimechanneldelivery.PendingAction, resolved runtimechanneldelivery.ResolvedAction) error {
	card, err := d.cards.GetDecisionCard(ctx, resolved.TargetCardID())
	if errors.Is(err, decisioncard.ErrNotFound) || err == nil && card.Status != decisioncard.StatusPending {
		return d.store.SettleUnappliedChannelAction(ctx, intent.Fact, runtimechanneldelivery.ActionStale)
	}
	if err != nil {
		return err
	}
	_, err = d.processCardAction(ctx, intent)
	return err
}

func (d *serveChannelDeliveryDispatcher) processInputSkip(ctx context.Context, intent runtimechanneldelivery.PendingAction,
	expected runtimechanneldelivery.ResolvedAction) error {
	resolved, progress, draft, err := d.store.PreviewChannelInputSkip(ctx, intent.Fact, intent.ReceivedAt)
	if err != nil {
		return err
	}
	if resolved != expected || draft.InputDraftID != resolved.Action.DraftID {
		return fmt.Errorf("channel skip changed before processing")
	}
	if progress.Complete {
		return d.processFinalCardSkip(ctx, intent, resolved, draft, progress)
	}
	_, err = d.store.AdvancePartialChannelInputSkip(ctx, intent.Fact, intent.ReceivedAt)
	return err
}

func (d *serveChannelDeliveryDispatcher) processDraftChoice(ctx context.Context, intent runtimechanneldelivery.PendingAction,
	resolved runtimechanneldelivery.ResolvedAction) error {
	candidate, text, progress, principalID, err := d.store.PreviewChosenChannelInputDraftText(ctx, intent.Fact, intent.ReceivedAt)
	if err != nil {
		if errors.Is(err, decisioncard.ErrDraftNotAuthority) {
			return d.store.SettleUnappliedChannelAction(ctx, intent.Fact, runtimechanneldelivery.ActionStale)
		}
		if errors.Is(err, decisioncard.ErrInvalidInput) {
			_, err = d.store.PlanChannelActionResponse(ctx, intent.Fact, resolved, "")
		}
		return err
	}
	if candidate.DraftID != resolved.Action.DraftID || candidate.CardID != resolved.Action.CardID ||
		text.PublicationID != resolved.Action.TextPublicationID {
		return fmt.Errorf("chosen channel draft changed before processing")
	}
	if progress.Complete {
		return d.processFinalCardText(ctx, text, candidate, progress, principalID, &intent)
	}
	_, err = d.store.AdvancePartialChosenChannelInputDraftText(ctx, intent.Fact, intent.ReceivedAt)
	return err
}

func (d *serveChannelDeliveryDispatcher) reconcileNativeInboxEntries(ctx context.Context) error {
	if d == nil || d.store == nil || d.cards == nil || d.mailbox == nil || d.proposedEffects == nil {
		return fmt.Errorf("channel inbox response owners are unavailable")
	}
	cursor := ""
	var failures error
	for {
		pending, err := d.store.ListPendingChannelTexts(ctx, cursor, 200)
		if err != nil {
			return errors.Join(failures, err)
		}
		for _, intent := range pending {
			if err := d.processPendingChannelText(ctx, intent); err != nil {
				failures = errors.Join(failures, fmt.Errorf("process channel text %s: %w", intent.PublicationID, err))
			}
		}
		if len(pending) < 200 {
			return failures
		}
		last := pending[len(pending)-1].PublicationID
		if last == cursor {
			return errors.Join(failures, fmt.Errorf("channel text pagination did not advance"))
		}
		cursor = last
	}
}

func (d *serveChannelDeliveryDispatcher) processPendingChannelText(ctx context.Context, intent runtimechanneldelivery.PendingText) error {
	if intent.Fact.EntryReference == "" {
		_, current, err := d.store.ResolveCurrentChannelText(ctx, intent.Fact)
		if err != nil {
			return err
		}
		if !current {
			return d.store.RejectUnboundChannelText(ctx, intent.Fact)
		}
		action, found, err := d.store.AdmitChannelReplyAction(ctx, intent.Fact)
		if err != nil {
			return err
		}
		if found {
			return d.processPendingChannelAction(ctx, action)
		}
		err = d.processPendingInputText(ctx, intent)
		var unsupported *runfork.SelectedForkControlUnsupported
		if errors.As(err, &unsupported) {
			return d.store.SettleUnsupportedChannelText(ctx, intent.Fact)
		}
		return err
	}
	entry, disposition, err := d.resolveInboxEntry(ctx, intent.Fact)
	if err != nil {
		return fmt.Errorf("resolve native inbox entry: %w", err)
	}
	if disposition == runtimechanneldelivery.InboxEntryRejected {
		return d.store.RejectInboxEntry(ctx, intent.Fact)
	}
	if disposition != runtimechanneldelivery.InboxEntryAccepted {
		return nil
	}
	content, err := d.inboxContent(ctx)
	if err != nil {
		return err
	}
	_, err = d.store.PlanInboxResponse(ctx, intent.Fact, entry, content)
	return err
}

func (d *serveChannelDeliveryDispatcher) processPendingInputText(ctx context.Context, intent runtimechanneldelivery.PendingText) error {
	var selected runtimechanneldelivery.InputDraftCandidate
	multiple := false
	cursor := ""
	for {
		candidates, next, err := d.store.ListCurrentChannelInputDrafts(ctx, intent.Fact, intent.ReceivedAt, cursor, 200)
		if err != nil {
			return err
		}
		for _, candidate := range candidates {
			if selected.DraftID != "" {
				multiple = true
				break
			}
			selected = candidate
		}
		if multiple {
			break
		}
		if next == "" {
			break
		}
		if next == cursor {
			return fmt.Errorf("channel input draft cursor did not advance")
		}
		cursor = next
	}
	if multiple {
		if intent.Fact.ReplyToReference != "" {
			return fmt.Errorf("quoted channel input selects multiple current drafts")
		}
		_, err := d.store.PlanChannelDraftChooser(ctx, intent.Fact, intent.ReceivedAt)
		return err
	}
	if selected.DraftID == "" {
		_, err := d.store.PlanChannelTextResponse(ctx, intent.Fact,
			"That reply does not match a current card prompt. Open inbox to review current actions.", "teaching")
		return err
	}
	progress, principalID, err := d.store.PreviewCurrentChannelInputDraftText(ctx, intent.Fact, intent.ReceivedAt, selected.DraftID)
	if err != nil {
		if errors.Is(err, decisioncard.ErrInvalidInput) {
			_, err = d.store.PlanChannelTextResponse(ctx, intent.Fact,
				"That answer does not match the requested field. Reply with a value of the required type, or use the card controls.", "teaching")
		}
		return err
	}
	if progress.Complete {
		return d.processFinalCardText(ctx, intent, selected, progress, principalID, nil)
	}
	_, err = d.store.AdvancePartialChannelInputDraftText(ctx, intent.Fact, intent.ReceivedAt, selected.DraftID)
	return err
}

func (d *serveChannelDeliveryDispatcher) inboxContent(ctx context.Context) (string, error) {
	if d == nil || d.cards == nil || d.mailbox == nil || d.proposedEffects == nil {
		return "", fmt.Errorf("channel inbox projection owners are unavailable")
	}
	owners := apiv1.DecisionCardHandlerOptions{
		Cards: d.cards, ProposedEffects: d.proposedEffects, Mailbox: d.mailbox,
	}
	entries := make([]runtimechanneldelivery.InboxEntry, 0)
	cursor := ""
	seen := map[string]struct{}{}
	unread := 0
	for {
		page, err := apiv1.ListMailboxProjectionPage(ctx, owners, decisioncard.StatusPending, cursor, 5)
		if err != nil {
			return "", err
		}
		if cursor == "" {
			unread = page.UnreadInformationalNotices
		}
		for _, item := range page.Items {
			entry, err := channelInboxProjectionEntry(item)
			if err != nil {
				return "", err
			}
			entries = append(entries, entry)
		}
		if page.NextCursor == "" {
			break
		}
		if page.NextCursor == cursor {
			return "", fmt.Errorf("channel inbox cursor did not advance")
		}
		if _, duplicate := seen[page.NextCursor]; duplicate {
			return "", fmt.Errorf("channel inbox cursor repeated")
		}
		seen[page.NextCursor] = struct{}{}
		cursor = page.NextCursor
	}
	return runtimechanneldelivery.InboxText(unread, entries, false)
}

func channelInboxProjectionEntry(item any) (runtimechanneldelivery.InboxEntry, error) {
	var err error
	projection, ok := item.(map[string]any)
	if !ok {
		return runtimechanneldelivery.InboxEntry{}, fmt.Errorf("mailbox projection item is not tagged")
	}
	var entry runtimechanneldelivery.InboxEntry
	switch projection["kind"] {
	case decisioncard.KindNotice:
		notice, ok := projection["notice"].(mailbox.V1Item)
		if !ok {
			return runtimechanneldelivery.InboxEntry{}, fmt.Errorf("mailbox notice projection is not typed")
		}
		entry, err = runtimechanneldelivery.InboxNoticeEntry(notice)
	case decisioncard.KindDecisionCard:
		card, ok := projection["decision_card"].(decisioncard.ListItem)
		if !ok {
			return runtimechanneldelivery.InboxEntry{}, fmt.Errorf("mailbox card projection is not typed")
		}
		entry, err = runtimechanneldelivery.InboxCardEntry(card)
	default:
		return runtimechanneldelivery.InboxEntry{}, fmt.Errorf("mailbox projection item has unknown kind")
	}
	if err != nil {
		return runtimechanneldelivery.InboxEntry{}, err
	}
	return entry, nil
}

func startServeChannelDelivery(ctx context.Context, owner *worklifetime.Process, dispatcher *serveChannelDeliveryDispatcher) error {
	if owner == nil || dispatcher == nil {
		return fmt.Errorf("channel delivery worker requires process and dispatcher")
	}
	lease, err := owner.Begin(ctx)
	if err != nil {
		return fmt.Errorf("admit channel delivery worker: %w", err)
	}
	go func() {
		defer func() { _ = lease.Done() }()
		workCtx := lease.Context()
		ticker := time.NewTicker(time.Second)
		nativeTicker := time.NewTicker(5 * time.Second)
		defer ticker.Stop()
		defer nativeTicker.Stop()
		if err := dispatcher.reconcileNativeInboxSettings(workCtx); err != nil && workCtx.Err() == nil {
			log.Printf("native inbox setting reconciliation: %v", err)
		}
		for {
			if err := dispatcher.reconcileNativeInboxEntries(workCtx); err != nil && workCtx.Err() == nil {
				log.Printf("channel inbox entry reconciliation: %v", err)
			}
			if err := dispatcher.reconcileDeliveries(workCtx); err != nil && workCtx.Err() == nil {
				log.Printf("channel delivery reconciliation: %v", err)
			}
			if err := dispatcher.reconcileCardActions(workCtx); err != nil && workCtx.Err() == nil {
				log.Printf("channel action reconciliation: %v", err)
			}
			select {
			case <-workCtx.Done():
				return
			case <-nativeTicker.C:
				if err := dispatcher.reconcileNativeInboxSettings(workCtx); err != nil && workCtx.Err() == nil {
					log.Printf("native inbox setting reconciliation: %v", err)
				}
			case <-ticker.C:
			}
		}
	}()
	return nil
}
