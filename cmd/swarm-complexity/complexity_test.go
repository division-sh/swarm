func TestIndependentThresholdsAndReporting(t *testing.T) {
	for _, metric := range []string{"cyclo", "cognit"} {
		for _, tc := range []struct {
			before, after int
			blocked       bool
		}{{29, 30, true}, {29, 31, true}, {30, 31, false}, {31, 29, false}, {30, 50, false}, {50, 200, false}} {
			d := compare(scoreFixture(metric, tc.before), scoreFixture(metric, tc.after))
			if d.Increased != tc.blocked || len(d.Changes) != 1 {
				t.Fatalf("%s %+v: %+v", metric, tc, d)
			}
		}
	}
	base, head := scoreFixture("cyclo", 30), scoreFixture("cognit", 30)
	if !compare(base, head).Increased || !compare(head, base).Increased {
		t.Fatal("one metric's decrease offset the other's growth")
	}
	head.Files = []fileRecord{{"p.go", "generated"}}
	base.Files = []fileRecord{{"p.go", "authored"}}
	d := compare(base, head)
	if len(d.AddedFiles) != 1 || len(d.RemovedFiles) != 1 {
		t.Fatal(d)
	}
}

func TestGitBaselineAndPolicyAdmission(t *testing.T) {
	ctx := context.Background()
	repo := fixtureRepo(t, map[string]string{"p.go": "package p\nfunc F(){}"})
	base := g(t, repo, "rev-parse", "HEAD")
	if err := run(ctx, options{repo: repo, head: "HEAD", base: base, update: true}, io.Discard); err != nil {
		t.Fatal(err)
	}
	head := commit(t, repo)
	if err := run(ctx, options{repo: repo, head: head, base: base, evidence: t.TempDir()}, io.Discard); err != nil {
		t.Fatal("first baseline:", err)
	}
	valid := measured(t, repo, head)
	data, _ := encode(valid)
	put(t, repo, baselinePath, strings.Replace(string(data), `"value":1`, `"value":999`, 1))
	inflated := commit(t, repo)
	if err := run(ctx, options{repo: repo, head: inflated, base: base}, io.Discard); err == nil {
		t.Fatal("self bump passed")
	}
	put(t, repo, baselinePath, string(data))
	commit(t, repo)
	if err := run(ctx, options{repo: repo, head: "HEAD", base: "missing-base"}, io.Discard); err == nil {
		t.Fatal("missing base passed")
	}
	valid.Policy.Threshold = 31
	changed, _ := encode(valid)
	put(t, repo, baselinePath, string(changed))
	policySHA := commit(t, repo)
	if err := checkBasePolicy(ctx, repo, policySHA, measured(t, repo, policySHA)); err == nil {
		t.Fatal("policy reset passed")
	}
	put(t, repo, baselinePath, string(data)+"{}")
	malformed := commit(t, repo)
	if err := checkBaseline(ctx, repo, malformed, data); err == nil {
		t.Fatal("trailing JSON accepted")
	}
	if err := checkBasePolicy(ctx, repo, malformed, measured(t, repo, malformed)); err == nil {
		t.Fatal("malformed base accepted")
	}
}

func TestRealGitIndependentGrowthAndPRHeadNotMerge(t *testing.T) {
	ctx := context.Background()
	for _, metric := range []string{"cyclo", "cognit"} {
		t.Run(metric, func(t *testing.T) {
			// Flat ifs yield cyclo N+1 and cognit N, exercising each boundary independently.
			n := 28
			if metric == "cognit" {
				n = 29
			}
			source := func(n int) string { return "package p\nfunc F(){" + strings.Repeat("if true {}\n", n) + "}" }
			repo := fixtureRepo(t, map[string]string{"p.go": source(n)})
			if err := run(ctx, options{repo: repo, head: "HEAD", update: true}, io.Discard); err != nil {
				t.Fatal(err)
			}
			base := commit(t, repo)
			g(t, repo, "checkout", "-qb", "feature")
			put(t, repo, "p.go", source(n+1))
			commit(t, repo)
			if err := run(ctx, options{repo: repo, head: "HEAD", update: true}, io.Discard); err != nil {
				t.Fatal(err)
			}
			head := commit(t, repo)
			var evidence bytes.Buffer
			err := run(ctx, options{repo: repo, head: head, base: base}, &evidence)
			if err == nil || !strings.Contains(err.Error(), "count increased") {
				t.Fatalf("self-raised measured baseline accepted: %v", err)
			}
			g(t, repo, "checkout", "master")
			put(t, repo, "merge_only.go", "package p\nfunc M(){}")
			commit(t, repo)
			g(t, repo, "merge", "--no-edit", "feature")
			merge := g(t, repo, "rev-parse", "HEAD")
			if merge == head {
				t.Fatal("no synthetic merge")
			}
			event := fmt.Sprintf(`{"pull_request":{"head":{"sha":%q},"base":{"sha":%q}}}`, head, base)
			put(t, repo, "event.json", event)
			evidence.Reset()
			err = run(ctx, options{repo: repo, head: merge, event: "pull_request", eventFile: filepath.Join(repo, "event.json")}, &evidence)
			if err == nil || !strings.Contains(evidence.String(), head) || strings.Contains(evidence.String(), "merge_only.go") {
				t.Fatalf("wrong PR snapshot: %v %s", err, evidence.String())
			}
		})
	}
}

func TestEventAdmission(t *testing.T) {
	head, base := strings.Repeat("a", 40), strings.Repeat("b", 40)
	for event, payload := range map[string]string{"push": fmt.Sprintf(`{"before":%q,"after":%q}`, base, head), "pull_request": fmt.Sprintf(`{"pull_request":{"head":{"sha":%q},"base":{"sha":%q}}}`, head, base)} {
		h, b, err := eventRevisions(event, []byte(payload))
		if err != nil || h != head || b != base {
			t.Fatalf("%s %s %s %v", event, h, b, err)
		}
		for _, invalid := range []string{"{}", "invalid", strings.ReplaceAll(payload, base, strings.Repeat("0", 40))} {
			if _, _, err := eventRevisions(event, []byte(invalid)); err == nil {
				t.Fatal("missing comparison accepted")
			}
		}
	}
	for _, event := range []string{"workflow_dispatch", "schedule"} {
		o := options{event: event, head: "HEAD"}
		if err := applyEvent(&o); err != nil || o.base != "" {
			t.Fatal("invented manual history", o, err)
		}
	}
	for _, o := range []options{{event: "push", update: true}, {event: "push", base: base}, {eventFile: "unexpected"}, {event: "unknown"}} {
		if err := applyEvent(&o); err == nil {
			t.Fatal("invalid options admitted", o)
		}
	}
}
