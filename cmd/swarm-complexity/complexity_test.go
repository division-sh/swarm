func fixtureRepo(t *testing.T, files map[string]string) string {
	t.Helper()
	repo := t.TempDir()
	g(t, repo, "init", "-b", "master")
	g(t, repo, "config", "user.name", "complexity-test")
	g(t, repo, "config", "user.email", "complexity-test@example.invalid")
	for path, content := range files {
		put(t, repo, path, content)
	}
	commit(t, repo)
	return repo
}

func g(t *testing.T, repo string, args ...string) string {
	t.Helper()
	b, err := git(context.Background(), repo, args...)
	if err != nil {
		t.Fatal(err)
	}
	return strings.TrimSpace(string(b))
}

func put(t *testing.T, repo, path, content string) {
	t.Helper()
	if err := writeFile(filepath.Join(repo, path), []byte(content)); err != nil {
		t.Fatal(err)
	}
}

func commit(t *testing.T, repo string) string {
	t.Helper()
	g(t, repo, "add", ".")
	g(t, repo, "commit", "-qm", "test: snapshot")
	return g(t, repo, "rev-parse", "HEAD")
}

func measured(t *testing.T, repo, ref string) baseline {
	t.Helper()
	sha := g(t, repo, "rev-parse", ref)
	b, err := measure(context.Background(), repo, sha, upstream)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestUpstreamPopulationAndSnapshot(t *testing.T) {
	const source = `package fixture
func init() {}
func init() { if true {} }
var A,B = func(){},func(){ if true {} }
type T[X any] struct{}
func (*T[X]) M() {}
func external()
var C = (func(){})
`
	repo := fixtureRepo(t, map[string]string{
		"testdata/.hidden/_support.go": source,
		"only_types.go":                "package fixture\ntype NoFunctions int\n",
		"tagged_windows.go":            "//go:build windows\n\npackage fixture\nfunc Windows() {}\n",
		"generated.go":                 "// Code generated by fixture. DO NOT EDIT.\npackage fixture\nfunc Excluded(){}\n",
		"not_generated.go":             "package fixture\n// Code generated by fixture. DO NOT EDIT.\nfunc Included(){}\n",
		"excluded_test.go":             "deliberately not Go",
	})
	b := measured(t, repo, "HEAD")
	if len(b.Metrics["cyclo"]) != 8 || len(b.Metrics["cognit"]) != 6 {
		t.Fatalf("populations: %#v", summaries(b))
	}
	var inits, literals, zeros int
	for _, row := range b.Metrics["cyclo"] {
		if row.Identity.Name == "init" {
			inits++
			if row.Identity.Occurrence != inits {
				t.Fatal(row)
			}
		}
		if row.Identity.Kind == "variable-literal" {
			literals++
			if row.Identity.Name != "A" || row.Identity.Occurrence != literals {
				t.Fatal(row)
			}
		}
	}
	for _, row := range b.Metrics["cognit"] {
		if row.Value == 0 {
			zeros++
		}
	}
	if inits != 2 || literals != 2 || zeros != 5 {
		t.Fatalf("init=%d literals=%d zero=%d", inits, literals, zeros)
	}
	classes := map[string]string{}
	for _, f := range b.Files {
		classes[f.Path] = f.Class
	}
	if classes["generated.go"] != "generated" || classes["not_generated.go"] != "authored" || classes["excluded_test.go"] != "test" {
		t.Fatal(classes)
	}
	put(t, repo, "testdata/.hidden/_support.go", "invalid dirty source")
	put(t, repo, "untracked.go", "invalid untracked source")
	if !reflect.DeepEqual(b, measured(t, repo, "HEAD")) {
		t.Fatal("working tree influenced measurement")
	}
	if err := os.Remove(filepath.Join(repo, "untracked.go")); err != nil {
		t.Fatal(err)
	}
	put(t, repo, "testdata/.hidden/_support.go", "\n\n"+source)
	commit(t, repo)
	if !reflect.DeepEqual(b, measured(t, repo, "HEAD")) {
		t.Fatal("line-only shifts changed identities")
	}
}

func TestSourceAdmission(t *testing.T) {
	for name, content := range map[string]string{
		"cyclo":       "package p\n//gocyclo:ignore\nfunc F(){}",
		"cyclo-space": "package p\n//gocyclo: ignore\nfunc F(){}",
		"cognit":      "package p\n//gocognit:ignore\nfunc F(){}",
		"line":        "package p\n//line imaginary.go:100\nfunc F(){}",
		"block-line":  "package p\n/*line imaginary.go:100*/func F(){}",
		"syntax":      "package p\nfunc broken(",
	} {
		t.Run(name, func(t *testing.T) {
			errCalled := false
			repo := fixtureRepo(t, map[string]string{"p.go": content})
			_, err := measure(context.Background(), repo, "HEAD", func(context.Context, string, string) ([]byte, error) { errCalled = true; return nil, nil })
			if err == nil || errCalled {
				t.Fatalf("admitted invalid source: called=%v err=%v", errCalled, err)
			}
		})
	}
	t.Run("no-functions", func(t *testing.T) {
		repo := fixtureRepo(t, map[string]string{"p.go": "package p\ntype T int"})
		b := measured(t, repo, "HEAD")
		if len(b.Metrics["cyclo"])+len(b.Metrics["cognit"]) != 0 {
			t.Fatal(b)
		}
	})
	for _, files := range []map[string]string{{"readme": "empty"}, {"p.go": "// Code generated by fixture. DO NOT EDIT.\npackage p"}} {
		repo := fixtureRepo(t, files)
		if _, err := measure(context.Background(), repo, "HEAD", upstream); err == nil {
			t.Fatal("empty authored inventory passed")
		}
	}
	t.Run("symlink", func(t *testing.T) {
		repo := fixtureRepo(t, map[string]string{"p.go": "package p"})
		if err := os.Symlink("p.go", filepath.Join(repo, "alias.go")); err != nil {
			t.Fatal(err)
		}
		commit(t, repo)
		if _, err := measure(context.Background(), repo, "HEAD", upstream); err == nil {
			t.Fatal("symlink passed")
		}
	})
}

func TestNormalizationRefusesMissingDuplicateAndForeignRows(t *testing.T) {
	expected := population{"/tmp/f.go:1:1": {identity{"f.go", "p", "declaration", "F", 1}, "F", "p"}}
	for _, raw := range []string{"", "1 p F /tmp/f.go:1:1\n1 p F /tmp/f.go:1:1", "1 p F invented.go:1:1", "1 p Wrong /tmp/f.go:1:1", "-1 p F /tmp/f.go:1:1", "no score"} {
		if _, err := normalize("cyclo", []byte(raw), expected); err == nil {
			t.Fatalf("accepted %q", raw)
		}
	}
	if _, err := normalize("cyclo", []byte("0 p F /tmp/f.go:1:1"), expected); err == nil {
		t.Fatal("zero cyclo")
	}
	if rows, err := normalize("cognit", []byte("0 p F /tmp/f.go:1:1"), expected); err != nil || len(rows) != 1 {
		t.Fatalf("%v %v", rows, err)
	}
	if _, err := normalize("cognit", []byte("1 p F /tmp/f.go:1:1"), population{}); err == nil {
		t.Fatal("unexpected nonempty output")
	}
}

