package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os/exec"
	"strconv"
	"strings"
)

type diagnosticPort struct{ name, operation, parameters, arguments, query, owner string }

func diagnosticPorts() []diagnosticPort {
	raw, err := exec.Command("git", "show", predecessor+":internal/serveapp/channel_delivery_settlement_diagnostic_test.go").Output()
	must(err)
	file, err := parser.ParseFile(token.NewFileSet(), "source.go", raw, parser.AllErrors)
	must(err)
	queries := map[string][]string{}
	for _, node := range file.Decls {
		fn, ok := node.(*ast.FuncDecl)
		if !ok {
			continue
		}
		ast.Inspect(fn, func(node ast.Node) bool {
			literal, ok := node.(*ast.BasicLit)
			if !ok || literal.Kind != token.STRING {
				return true
			}
			value, err := strconv.Unquote(literal.Value)
			must(err)
			if strings.HasPrefix(strings.TrimSpace(value), "SELECT") {
				queries[fn.Name.Name] = append(queries[fn.Name.Name], value)
			}
			return true
		})
	}
	if len(queries["logUnsettledChannelDeliveryPlans"]) != 1 || len(queries["readChannelDeliverySettlementDiagnostic"]) != 6 {
		panic("signed channel diagnostic query inventory changed")
	}
	q := queries["readChannelDeliverySettlementDiagnostic"]
	return []diagnosticPort{
		{"ReadUnsettledChannelPlanIDsStorage", "ReadUnsettledChannelPlanIDsStorageTx", "", "", queries["logUnsettledChannelDeliveryPlans"][0], "channel"},
		{"ReadChannelPlanSourceDefaultStorage", "ReadChannelPlanSourceDefaultStorageTx", "deliveryID string", "deliveryID", q[0], "channel"},
		{"ReadChannelActivationDiagnosticStorage", "ReadChannelActivationDiagnosticStorageTx", "deliveryID string", "deliveryID", q[1], "channel"},
		{"ReadChannelRenderDiagnosticStorage", "ReadChannelRenderDiagnosticStorageTx", "deliveryID string", "deliveryID", q[2], "channel"},
		{"ReadChannelReceiptDiagnosticStorage", "ReadChannelReceiptDiagnosticStorageTx", "deliveryID string", "deliveryID", q[3], "channel"},
		{"ReadChannelOperationDiagnosticStorage", "ReadChannelOperationDiagnosticStorageTx", "", "", q[4], "effect"},
		{"ReadChannelAttemptDiagnosticStorage", "ReadChannelAttemptDiagnosticStorageTx", "operationID string", "operationID", q[5], "effect"},
	}
}

func generateDiagnostics() {
	byOwner := map[string]string{"channel": "channeldelivery", "effect": "effectpersistence"}
	for owner, pkg := range byOwner {
		source := `// Code generated by migrate-channel-settlement -ports; DO NOT EDIT.
package ` + pkg + `
import("context";"database/sql")
func scanChannelSettlementDiagnosticRows(rows *sql.Rows)([]map[string]string,error){defer rows.Close();columns,err:=rows.Columns();if err!=nil{return nil,err};var result []map[string]string;for rows.Next(){values,targets:=make([]sql.NullString,len(columns)),make([]any,len(columns));for index:=range values {targets[index]=&values[index]};if err:=rows.Scan(targets...);err!=nil{return nil,err};row:=map[string]string{};for index,column:=range columns {if values[index].Valid {row[column]=values[index].String}};result=append(result,row)};return result,rows.Err()}
`
		for _, d := range diagnosticPorts() {
			if d.owner != owner {
				continue
			}
			source += fmt.Sprintf("func %s(ctx context.Context,tx *sql.Tx%s)([]map[string]string,error){rows,err:=tx.QueryContext(ctx,%s%s);if err!=nil{return nil,err};return scanChannelSettlementDiagnosticRows(rows)}\n", d.operation, prefixed(d.parameters), strconv.Quote(d.query), prefixed(d.arguments))
		}
		writeGo("internal/store/internal/backend/"+pkg+"/channel_settlement_diagnostics.go", source)
	}
	generateSelectedDiagnostics()
}

func generateSelectedDiagnostics() {
	raw, err := exec.Command("git", "show", predecessor+":internal/serveapp/channel_delivery_settlement_diagnostic_test.go").Output()
	must(err)
	file, err := parser.ParseFile(token.NewFileSet(), "source.go", raw, parser.AllErrors)
	must(err)
	var generated []string
	for _, node := range file.Decls {
		fn, ok := node.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "logUnsettledChannelDeliveryPlans" && fn.Name.Name != "readChannelDeliverySettlementDiagnostic" {
			continue
		}
		source := string(raw[fn.Pos()-1 : fn.End()-1])
		source = strings.Replace(source, "db *sql.DB", "reader storetest.ChannelSettlementObservation", 1)
		if fn.Name.Name == "logUnsettledChannelDeliveryPlans" {
			source = strings.Replace(source, "func logUnsettledChannelDeliveryPlans", "func logSelectedUnsettledChannelDeliveryPlans", 1)
			d := diagnosticPorts()[0]
			source = replaceExact(source, "readChannelDeliveryDiagnosticRows(ctx, db, `"+d.query+"`)", "reader.ReadUnsettledChannelPlanIDsStorage(ctx)")
			source = replaceExact(source, "readChannelDeliverySettlementDiagnostic(ctx, db,", "readSelectedChannelDeliverySettlementDiagnostic(ctx, reader,")
		} else {
			source = selectedEvidenceSource(source)
		}
		generated = append(generated, source)
	}
	writeGo("internal/serveapp/channel_selected_settlement_diagnostic_test.go", `// Code generated by migrate-channel-settlement -ports; DO NOT EDIT.
package serveapp
import("context";"encoding/json";"fmt";"testing";"time";"github.com/division-sh/swarm/internal/store/storetest")
`+strings.Join(generated, "\n")+`
func waitSelectedChannelDeliverySendsSettled(t *testing.T,reader storetest.ChannelSettlementObservation){t.Helper();deadline:=time.Now().Add(20*time.Second);for {count,err:=reader.CountUnsettledResponsibilitiesStorage(context.Background());if err!=nil{t.Fatal(err)};if count==0{return};if time.Now().After(deadline){logSelectedUnsettledChannelDeliveryPlans(t,reader);t.Fatal("initial public deliveries never settled")};time.Sleep(20*time.Millisecond)}}
`)
}

func selectedEvidenceSource(source string) string {
	source = strings.Replace(source, "func readChannelDeliverySettlementDiagnostic", "func readSelectedChannelDeliverySettlementDiagnostic", 1)
	start, end := strings.Index(source, "queries :="), strings.Index(source, "for _, query := range queries")
	if start < 0 || end <= start {
		panic("signed diagnostic grouping changed")
	}
	list := `queries:=[]struct{name string;read func(context.Context,string)([]map[string]string,error)}{
{"plan_source_default",reader.ReadChannelPlanSourceDefaultStorage},{"activations",reader.ReadChannelActivationDiagnosticStorage},{"renders",reader.ReadChannelRenderDiagnosticStorage},{"receipts",reader.ReadChannelReceiptDiagnosticStorage},};`
	source = source[:start] + list + source[end:]
	source = replaceExact(source, "readChannelDeliveryDiagnosticRows(ctx, db, query.query, deliveryID)", "query.read(ctx,deliveryID)")
	for _, d := range diagnosticPorts()[5:] {
		before := "readChannelDeliveryDiagnosticRows(ctx, db, `" + d.query + "`"
		after := "reader." + d.name + "(ctx"
		if d.arguments != "" {
			before += ", operation[\"operation_id\"]"
			after += ",operation[\"operation_id\"]"
		}
		source = replaceExact(source, before+")", after+")")
	}
	return source
}
