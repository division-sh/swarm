func parameterTypes(parameters string) string {
	if parameters == "" {
		return ""
	}
	parts := strings.Split(parameters, ",")
	last := ""
	for index := len(parts) - 1; index >= 0; index-- {
		fields := strings.Fields(parts[index])
		if len(fields) == 2 {
			last = fields[1]
		} else if len(fields) != 1 || last == "" {
			panic("invalid fixed port parameters")
		}
		parts[index] = last
	}
	return strings.Join(parts, ",")
}

func prefixed(value string) string {
	if value == "" {
		return ""
	}
	return "," + value
}

func writeGo(path, source string) {
	raw, err := format.Source([]byte(source))
	must(err)
	must(os.WriteFile(path, raw, 0644))
}
