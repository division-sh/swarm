func generateOwners(before []byte, scanner string) {
	positive := sqlLiterals(declaration(before, "TestChannelDeliveryBudgetNoticePublicJourney"))
	if len(positive) != 2 {
		panic("signed positive budget witness inventory changed")
	}
	for _, p := range projections {
		body := scanner + "\n"
		scan := "scanChannelBudgetDiagnosticRows"
		if p.ExistingScanner {
			body, scan = "", "scanChannelSettlementDiagnosticRows"
		}
		body += fmt.Sprintf(`func ReadChannelBudget%sDiagnosticsStorageTx(ctx context.Context,tx *sql.Tx)([]map[string]string,error){rows,err:=tx.QueryContext(ctx,%q);if err!=nil{return nil,err};return %s(rows)}
`, p.Name, p.Query, scan)
		body += positiveOwner(p.Name, positive)
		if p.Package == "delivery" {
			original := signed(p.File)
			expected := string(original) + "\n// Fixed channel budget failure evidence; no executable-delivery interpretation.\n" + body
			current, err := os.ReadFile(p.File)
			must(err)
			if string(current) != string(original) && formatted(current) != formatted([]byte(expected)) {
				panic("closed delivery owner changed outside this finite append")
			}
			writeGo(p.File, expected)
			continue
		}
		writeGo(p.File, fmt.Sprintf("// Code generated by migrate-budget-diagnostics -write; DO NOT EDIT.\npackage %s\nimport(\"context\";\"database/sql\")\n%s", p.Package, body))
	}
}

