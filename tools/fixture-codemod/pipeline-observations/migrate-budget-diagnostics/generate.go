func privatePort(name, result, operation string) string {
	return fmt.Sprintf(`func %sForTest(ctx context.Context,selected any)(%s,error){var out %s;if err:=validateChannelObservationOwner(selected);err!=nil{return out,err};missing:=false;err:=readServedDeliveryObservation(ctx,selected,func(ctx context.Context,tx *sql.Tx)error{var err error;out,err=%s(ctx,tx);if err==sql.ErrNoRows{missing=true;return nil};return err});if err==nil&&missing{err=sql.ErrNoRows};return out,err}
`, name, result, result, operation)
}

func publicPort(name, result string) string {
	return fmt.Sprintf(`func(o channelObservation)%s(ctx context.Context)(%s,error){var out %s;missing:=false;err:=o.selected.InspectSnapshot(ctx,func(ctx context.Context)error{var err error;out,err=private.%sForTest(ctx,o.selected);if err==sql.ErrNoRows{missing=true;return nil};return err});if err==nil&&missing{err=sql.ErrNoRows};return out,err}
`, name, result, result, name)
}

func formatted(raw []byte) string {
	formatted, err := format.Source(raw)
	must(err)
	return strings.TrimSpace(string(formatted))
}

func appendOriginal(path, addition string) {
	prior := signed(path)
	expected := string(prior) + addition
	actual, err := os.ReadFile(path)
	must(err)
	if string(actual) != string(prior) && formatted(actual) != formatted([]byte(expected)) {
		panic("original bridge changed outside its finite named append: " + path)
	}
	writeGo(path, expected)
}
